// Tiny 3x5 bitmap font for panel labels.
"use strict";
const G = {
  A: ["010","101","111","101","101"], B: ["110","101","110","101","110"],
  C: ["011","100","100","100","011"], D: ["110","101","101","101","110"],
  E: ["111","100","110","100","111"], F: ["111","100","110","100","100"],
  H: ["101","101","111","101","101"], L: ["100","100","100","100","111"],
  M: ["101","111","111","101","101"], N: ["101","111","111","111","101"],
  O: ["010","101","101","101","010"], P: ["110","101","110","100","100"],
  R: ["110","101","110","101","101"], S: ["011","100","010","001","110"],
  T: ["111","010","010","010","010"], V: ["101","101","101","101","010"],
  "1": ["010","110","010","010","111"], "-": ["000","000","111","000","000"],
  " ": ["000","000","000","000","000"],
};
function drawText(img, width, x0, y0, text, scale, color) {
  let cx = x0;
  for (const ch of text.toUpperCase()) {
    const g = G[ch] || G[" "];
    for (let y = 0; y < 5; y++)
      for (let x = 0; x < 3; x++)
        if (g[y][x] === "1")
          for (let sy = 0; sy < scale; sy++)
            for (let sx = 0; sx < scale; sx++) {
              const px = cx + x * scale + sx, py = y0 + y * scale + sy;
              const i = (py * width + px) * 3;
              img[i] = color[0]; img[i + 1] = color[1]; img[i + 2] = color[2];
            }
    cx += 4 * scale;
  }
}
module.exports = { drawText };
